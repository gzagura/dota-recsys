def build_alias_lookup(name_to_id: dict[str, int]) -> dict[str, int]:
    """Нормализованный алиас -> hero_id.

    name_to_id: каноническое localized_name -> hero_id.

    Псевдонимы неизвестных героев пропускаются молча: справочник обновляется
    Valve, и новый патч не должен ронять сайт. А вот один алиас на двух
    героев — это ошибка словаря, и она поднимается сразу: молча выбранный
    «первый попавшийся» герой давал бы неверный пик без всякого сигнала.
    """
    lookup: dict[str, int] = {}
    owner: dict[str, str] = {}
    for canonical, variants in ALIASES.items():
        hero_id = name_to_id.get(canonical)
        if hero_id is None:
            continue
        for variant in variants:
            key = normalize(variant)
            if key in owner and owner[key] != canonical:
                raise ValueError(
                    f"Алиас '{variant}' назначен двум героям: {owner[key]} и {canonical}"
                )
            owner[key] = canonical
            lookup[key] = hero_id
    return lookup
